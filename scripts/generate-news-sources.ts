import { writeFile } from 'node:fs/promises'
import { getNewsFeedPresets, newsCollectorSchema, type NewsCollectorConfig } from '../src/domain/news/config.js'

type Feed = NewsCollectorConfig['feeds'][number]
const key = (feed: Feed) => JSON.stringify([feed.source, feed.url, feed.rsshubRoute ?? null])
const defaults = new Map(newsCollectorSchema.parse({}).feeds.map((feed) => [key(feed), feed.enabled]))
const feeds = getNewsFeedPresets()
const regions: Record<string, string> = { cn: '中国内地', hk: '中国香港', us: '美国', europe: '欧洲', jp: '日本', asia: '亚太', global: '全球' }
const markets: Record<string, string> = { markets: '股票', macro: '宏观', fx: '外汇', commodities: '商品', bonds: '债券', funds: '基金', crypto: '加密资产', ai: '人工智能', tech: '科技' }
const cell = (value: string) => value.replaceAll('|', '\\|').replaceAll('\n', ' ')
const rows = feeds.map((feed) => {
  const enabled = defaults.get(key(feed))
  return '| ' + [feed.name, feed.rsshubRoute ? 'RSSHub' : 'RSS / Atom 直连', feed.source, feed.rsshubRoute ?? feed.url, feed.regions.map(value => regions[value] ?? value).join('、'), feed.markets.map(value => markets[value] ?? value).join('、'), enabled === undefined ? '按需添加' : enabled ? '初始启用' : '初始停用'].map(cell).join(' | ') + ' |'
}).join('\n')
const regionRows = Object.entries(regions).map(([value, name]) => {
  const matches = feeds.filter(feed => feed.regions.includes(value))
  return '| ' + [name, String(matches.length), matches.map(feed => feed.name).join('、')].map(cell).join(' | ') + ' |'
}).join('\n')

